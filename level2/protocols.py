def find_weakness(text: str):
    """ابحث عن أول نقطة ضعف تطابق نص المستخدم عبر الكلمات المفتاحية."""
    t = (text or "").lower()
    best, best_score = None, 0
    for w in WEAKNESSES:
        score = sum(1 for kw in w["keywords"] if kw in t)
        if score > best_score:
            best, best_score = w, score
    return best


def find_phrase(query: str):
    """ابحث عن عبارة توجيهية مناسبة لوصف الموقف."""
    t = (query or "").lower()
    for p in PHRASES:
        key = p["situation"]
        if key and key in t:
            return p
    # مطابقة جزئية بكلمات الموقف
    words = [w for w in t.split() if len(w) > 3]
    for p in PHRASES:
        if any(w in p["situation"] or p["situation"] in t for w in words):
            return p
    return None
